-- Migração aditiva e não destrutiva: registo de acessos a contas para a Sala do ADM.
-- Execute no SQL Editor do projeto Supabase depois de confirmar o email do ADM.
create table if not exists public.account_access_logs (
  id bigint generated by default as identity primary key,
  owner_uid uuid not null,
  account_id text not null,
  email text,
  house_name text not null default '',
  role text not null check (role in ('owner', 'staff')),
  accessed_at timestamptz not null default now()
);
create index if not exists account_access_logs_accessed_at_idx
  on public.account_access_logs (accessed_at desc);
create index if not exists account_access_logs_owner_uid_idx
  on public.account_access_logs (owner_uid, accessed_at desc);
alter table public.account_access_logs enable row level security;
revoke all on public.account_access_logs from anon, authenticated;

create or replace function public.log_owner_access(p_account_id text, p_house_name text)
returns void language plpgsql security definer set search_path = public, auth as $$
declare v_uid uuid := auth.uid(); v_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
begin
  if v_uid is null then raise exception 'auth required'; end if;
  if coalesce(trim(p_account_id), '') = '' then raise exception 'account id required'; end if;
  if not exists (select 1 from public.houses h where h.user_id = v_uid and h.account ->> 'id' = p_account_id) then raise exception 'account does not match session'; end if;
  -- Evita duplicados se React monta duas vezes ou a app reabre rapidamente.
  if exists (select 1 from public.account_access_logs l where l.owner_uid = v_uid and l.account_id = p_account_id and l.role = 'owner' and l.accessed_at > now() - interval '2 minutes') then return; end if;
  insert into public.account_access_logs(owner_uid, account_id, email, house_name, role)
  values (v_uid, left(p_account_id, 80), nullif(left(v_email, 254), ''), left(coalesce(p_house_name, ''), 120), 'owner');
end $$;

create or replace function public.log_staff_access(p_token text, p_account_id text, p_house_name text)
returns void language plpgsql security definer set search_path = public, auth as $$
declare v_staff public.staff_access%rowtype; v_email text;
begin
  v_staff := public._staff_ctx(p_token);
  if v_staff.owner_uid is null then raise exception 'staff access denied'; end if;
  if coalesce(trim(p_account_id), '') = '' then raise exception 'account id required'; end if;
  if not exists (select 1 from public.houses h where h.user_id = v_staff.owner_uid and h.account ->> 'id' = p_account_id) then raise exception 'account does not match staff session'; end if;
  if exists (select 1 from public.account_access_logs l where l.owner_uid = v_staff.owner_uid and l.account_id = p_account_id and l.role = 'staff' and l.accessed_at > now() - interval '2 minutes') then return; end if;
  select lower(coalesce(h.account ->> 'login', '')) into v_email from public.houses h where h.user_id = v_staff.owner_uid;
  insert into public.account_access_logs(owner_uid, account_id, email, house_name, role)
  values (v_staff.owner_uid, left(p_account_id, 80), nullif(left(coalesce(v_email, ''), 254), ''), left(coalesce(p_house_name, ''), 120), 'staff');
end $$;

create or replace function public.adm_access_logs()
returns table(id bigint, account_id text, email text, house_name text, role text, accessed_at timestamptz)
language plpgsql security definer set search_path = public, auth as $$
begin
  if lower(coalesce(auth.jwt() ->> 'email', '')) <> 'tvvibeoficial@gmail.com' then
    raise exception 'ADM access required';
  end if;
  return query select l.id, l.account_id, l.email, l.house_name, l.role, l.accessed_at
    from public.account_access_logs l order by l.accessed_at desc limit 500;
end $$;

revoke all on function public.log_owner_access(text, text) from public, anon;
revoke all on function public.log_staff_access(text, text, text) from public, anon;
revoke all on function public.adm_access_logs() from public, anon;
grant execute on function public.log_owner_access(text, text) to authenticated;
grant execute on function public.log_staff_access(text, text, text) to anon, authenticated;
grant execute on function public.adm_access_logs() to authenticated;


-- Comentários das comunidades. As publicações do ADM continuam dentro de adm_global;
-- esta tabela guarda apenas comentários de utilizadores e nunca palavras-passe/tokens.
create table if not exists public.community_comments (
  id bigint generated by default as identity primary key,
  owner_uid uuid not null,
  room_id text not null,
  account_id text not null,
  author_name text not null default '',
  body text not null,
  created_at timestamptz not null default now()
);
create index if not exists community_comments_room_idx
  on public.community_comments (room_id, created_at desc);
alter table public.community_comments enable row level security;
revoke all on public.community_comments from anon, authenticated;

create or replace function public.community_list_comments(p_room_id text)
returns table(id bigint, room_id text, author_name text, body text, created_at timestamptz)
language sql stable security definer set search_path = public as $$
  select c.id, c.room_id, c.author_name, c.body, c.created_at
  from public.community_comments c
  where c.room_id = left(coalesce(p_room_id, ''), 80)
  order by c.created_at desc limit 200
$$;

create or replace function public.community_add_comment(
  p_room_id text, p_account_id text, p_author_name text, p_body text, p_staff_token text default null
) returns jsonb language plpgsql security definer set search_path = public, auth as $$
declare v_uid uuid; v_staff public.staff_access%rowtype; v_row public.community_comments%rowtype;
begin
  if length(trim(coalesce(p_body, ''))) < 1 or length(p_body) > 1000 then raise exception 'O comentário deve ter entre 1 e 1000 caracteres.'; end if;
  if coalesce(p_staff_token, '') <> '' then
    v_staff := public._staff_ctx(p_staff_token);
    if v_staff.owner_uid is null then raise exception 'Sessão de funcionário inválida ou bloqueada.'; end if;
    v_uid := v_staff.owner_uid;
  else
    v_uid := auth.uid();
    if v_uid is null then raise exception 'Entre na sua conta para comentar.'; end if;
    if not exists (select 1 from public.houses h where h.user_id = v_uid and h.account ->> 'id' = p_account_id) then
      raise exception 'A conta não corresponde à sessão autenticada.';
    end if;
  end if;
  insert into public.community_comments(owner_uid, room_id, account_id, author_name, body)
  values (v_uid, left(coalesce(p_room_id, ''), 80), left(coalesce(p_account_id, ''), 80), left(coalesce(p_author_name, 'Utilizador'), 60), trim(p_body))
  returning * into v_row;
  return jsonb_build_object('id', v_row.id, 'room_id', v_row.room_id, 'account_id', v_row.account_id,
    'author_name', v_row.author_name, 'body', v_row.body, 'created_at', v_row.created_at);
end $$;

revoke all on function public.community_list_comments(text) from public;
revoke all on function public.community_add_comment(text, text, text, text, text) from public;
grant execute on function public.community_list_comments(text) to anon, authenticated;
grant execute on function public.community_add_comment(text, text, text, text, text) to authenticated;
-- O funcionário não tem login Supabase próprio; a função valida o token de equipa.
grant execute on function public.community_add_comment(text, text, text, text, text) to anon;


-- Consulta e edição segura da cobrança de contas que não existem no armazenamento local do ADM.
create or replace function public.adm_list_accounts()
returns table(owner_uid uuid, account_id text, email text, house_name text, billing jsonb, updated_at timestamptz)
language plpgsql security definer set search_path = public, auth as $$
begin
  if lower(coalesce(auth.jwt() ->> 'email', '')) <> 'tvvibeoficial@gmail.com' then raise exception 'ADM access required'; end if;
  return query select h.user_id, coalesce(h.account ->> 'id', ''), coalesce(h.account ->> 'login', ''),
    coalesce(h.account ->> 'houseName', ''), coalesce(h.admin -> 'billing', '{}'::jsonb), h.updated_at
    from public.houses h where coalesce(h.account ->> 'id', '') <> '' order by h.updated_at desc limit 500;
end $$;

create or replace function public.adm_set_billing(p_owner_uid uuid, p_billing jsonb)
returns jsonb language plpgsql security definer set search_path = public, auth as $$
declare n integer;
begin
  if lower(coalesce(auth.jwt() ->> 'email', '')) <> 'tvvibeoficial@gmail.com' then raise exception 'ADM access required'; end if;
  if p_billing is null or jsonb_typeof(p_billing) <> 'object' then raise exception 'invalid billing data'; end if;
  update public.houses set admin = jsonb_set(coalesce(admin, '{}'::jsonb), '{billing}', p_billing, true),
    rev = rev + 1, updated_at = now() where user_id = p_owner_uid;
  get diagnostics n = row_count;
  if n <> 1 then return jsonb_build_object('ok', false); end if;
  return jsonb_build_object('ok', true);
end $$;
revoke all on function public.adm_list_accounts() from public, anon;
revoke all on function public.adm_set_billing(uuid, jsonb) from public, anon;
grant execute on function public.adm_list_accounts() to authenticated;
grant execute on function public.adm_set_billing(uuid, jsonb) to authenticated;
